import { randomUUID } from 'node:crypto'
import { AuthenChain, type RegulatoryMetadataV1 } from '@authenchain/node'

const authenchainApiKey = process.env.AUTHENCHAIN_API_KEY

if (!authenchainApiKey) {
  throw new Error('AUTHENCHAIN_API_KEY is required')
}

const ac = new AuthenChain({
  apiKey: authenchainApiKey,
  baseUrl: process.env.AUTHENCHAIN_BASE_URL,
  timeoutMs: 10_000,
})

function classifyRiskContextFromPolicy(workflowId: string): RegulatoryMetadataV1['risk_context'] {
  if (workflowId === 'customer-support-disclosure') return 'limited'
  return 'unknown'
}

async function main() {
  const workflowId = 'customer-support-disclosure'
  const output = 'This response was generated by an AI assistant and reviewed by the support workflow.'
  const regulatory: RegulatoryMetadataV1 = {
    schema_version: 'regulatory.v1',
    ai_generated: true,
    jurisdiction: 'EU',
    regulatory_context: ['eu_ai_act_article_50'],
    content_type: 'text',
    model_provider: 'openai',
    model_name: 'gpt-4.1',
    system_purpose: 'customer_support_response',
    risk_context: classifyRiskContextFromPolicy(workflowId),
    human_reviewed: false,
    disclosure_required: true,
    disclosure_applied: true,
    label_type: 'human_visible',
    policy_version: 'ai-disclosure-policy-v1',
  }

  const provenance = await ac.sign({
    content: output,
    requestId: 'demo-regulatory-metadata-sign',
    correlationId: 'partner-poc-regulatory-metadata',
    idempotencyKey: `regulatory-metadata:${workflowId}:example-1`,
    metadata: {
      schema_version: '1.0',
      issuer: 'regulatory-metadata-demo',
      content_type: 'text',
      created_at: new Date().toISOString(),
      nonce: randomUUID(),
      trace_id: randomUUID(),
      model: 'support-workflow-v1',
      regulatory,
      extra: {
        workflowId,
        source: 'server-backend',
      },
    },
  })

  const verification = await ac.verify({
    content: output,
    provenance,
    requestId: 'demo-regulatory-metadata-verify',
    correlationId: 'partner-poc-regulatory-metadata',
  })

  let evidencePackStatus: string | null = null
  try {
    const evidencePack = await ac.exportEvidencePack({
      traceId: provenance.traceId,
      requestId: 'demo-regulatory-metadata-evidence-pack',
      correlationId: 'partner-poc-regulatory-metadata',
    })
    evidencePackStatus = evidencePack.trustedStatus
  } catch (error) {
    evidencePackStatus = 'not_available_in_this_environment'
  }

  console.log(
    JSON.stringify(
      {
        traceId: provenance.traceId,
        verified: verification.verified,
        reasonCodes: verification.reasonCodes,
        regulatory: provenance.metadata.regulatory,
        evidencePackStatus,
      },
      null,
      2
    )
  )
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
